let cache: { day: string; posts: PostRow[] } | null = null;

/** 날짜가 늘 '오늘' 기준으로 보이도록 날마다 다시 만든다 */
export function demoPosts(): PostRow[] {
  const today = todayKST();
  if (cache?.day === today) return cache.posts;
  const now = Date.now();
  const posts = SEEDS.map(({ startIn, deadlineIn, hoursAgo, status, ...s }) => {
    const created = new Date(now - hoursAgo * 3_600_000);
    return {
      ...s,
      start_date: addDays(today, startIn),
      deadline: addDays(today, deadlineIn),
      status: status ?? "recruiting",
      closed_reason: status === "closed" ? "deadline" : null,
      created_at: created,
      updated_at: created,
    };
  });
  cache = { day: today, posts };
  return posts;
}
